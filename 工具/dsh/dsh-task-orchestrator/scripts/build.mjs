import { stripTypeScriptTypes } from 'node:module'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
const root = new URL('../', import.meta.url)
await mkdir(new URL('lib/', root), { recursive: true })
const host = await readFile(new URL('src/host.ts', root), 'utf8')
const orchestrator = await readFile(new URL('src/orchestrator.ts', root), 'utf8')
const client = await readFile(new URL('src/client.ts', root), 'utf8')
const templateSpace = await readFile(new URL('src/template-space.ts', root), 'utf8')
const topologyStore = await readFile(new URL('src/topology-store.ts', root), 'utf8')
const topologyGroups = await readFile(new URL('src/topology-groups.ts', root), 'utf8')
const templateStore = await readFile(new URL('src/template-store.ts', root), 'utf8')
const hostJS = stripTypeScriptTypes(host, { mode: 'strip' })
const orchestratorJS = stripTypeScriptTypes(orchestrator, { mode: 'strip' })
const clientJS = stripTypeScriptTypes(client, { mode: 'strip' }).replace('export const inject', 'const inject').replace('export function apply', 'function apply')
const templateSpaceJS = stripTypeScriptTypes(templateSpace, { mode: 'strip' })
const topologyStoreJS = stripTypeScriptTypes(topologyStore, { mode: 'strip' })
const templateStoreJS = stripTypeScriptTypes(templateStore, { mode: 'strip' })
await writeFile(new URL('lib/index.js', root), hostJS)
await writeFile(new URL('lib/orchestrator.js', root), orchestratorJS)
await writeFile(new URL('lib/topology-store.js', root), topologyStoreJS)
await writeFile(new URL('lib/template-store.js', root), templateStoreJS)
await writeFile(new URL('lib/topology-groups.js', root), stripTypeScriptTypes(topologyGroups, { mode: 'strip' }))
await writeFile(new URL('lib/client.js', root), `window.__ModuleLoader__.load({ id: 'dsh-task-orchestrator', factory: (require) => {\n${stripTypeScriptTypes(topologyGroups, { mode: 'strip' }).replace('export function groupTopologies', 'function groupTopologies')}\n${clientJS.replace('function Panel(', `${templateSpaceJS}\nfunction Panel(`)}\nreturn { apply, inject }\n} })\n`)
